#!/usr/bin/env python3
"""Turn a graph blob into a C header the targets compile in.

The target chains cannot open files, so the blob travels as bytes. Bytes rather than
float literals on purpose: a literal would have to be re-parsed by the target's libc,
and `1e-7` round-tripping is exactly the kind of thing that silently differs between
newlib and glibc (the same reason `emit_kat_image.py` keeps raw bytes).

This is what makes the case real rather than staged: the **same file** the host gtest
reads is the one the Cortex-M parses, so "it ran on the target" cannot mean "a
hand-maintained C array that used to match the model".

Usage: emit_blob_image.py [--name kat_k2_blob] <model.blob> <out.h>
"""
import argparse
import hashlib
import pathlib
import sys

MAGIC = b"INFRKAT\0"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("blob")
    ap.add_argument("out")
    ap.add_argument("--name", default="kat_blob", help="C identifier of the array")
    args = ap.parse_args()

    data = pathlib.Path(args.blob).read_bytes()
    if data[:8] != MAGIC:
        print(f"emit_blob_image: {args.blob} is not an INFRKAT blob", file=sys.stderr)
        return 1
    (version,) = [int.from_bytes(data[8:12], "little")]
    if version != 2:
        print(f"emit_blob_image: unsupported version {version} (expected 2)", file=sys.stderr)
        return 1

    upper = args.name.upper()
    out = [
        "/* Generated by workspace/qa/prep/emit_blob_image.py -- do not edit.",
        f" * {pathlib.Path(args.blob).name} as bytes: the target parses this with",
        " * workspace/qa/kat/blob_graph.c, the same blob the host gtest reads.",
        " * 由 workspace/qa/prep/emit_blob_image.py 生成，不要手改。 */",
        "#pragma once",
        "",
        f"#define {upper}_LEN {len(data)}u",
        f'#define {upper}_SHA256 "{hashlib.sha256(data).hexdigest()}"',
        "",
        f"static const unsigned char {args.name}[{upper}_LEN] = {{",
    ]
    row = []
    for byte in data:
        row.append(f"0x{byte:02X}")
        if len(row) == 12:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    out.append("};")
    out.append("")

    target = pathlib.Path(args.out)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"[emit_blob_image] wrote {target} ({len(data)} B)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
