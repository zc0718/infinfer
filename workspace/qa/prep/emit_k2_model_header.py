#!/usr/bin/env python3
"""Turn the `k2_conv_micro` blob and its input into a C header for the KAT chain.

The target-side chain cannot read files, so the weights and the input are compiled in
as plain float arrays. Decoding happens here rather than in C on purpose: the blob
reader already exists (host gtest `graph_kat_k2_conv_micro.cpp`) and a second copy of
a bounds-checked parser is exactly the kind of duplication that drifts.

Only the *inputs* are baked here. The expectation is not: it is produced by running
the chain on the host (`--emit`), so `gate/kat` judges cross-target bitwise equality
while the numerical agreement with numpy is judged separately by the host KAT.

Usage: emit_k2_model_header.py <blob> <input.bin> <out.h>
"""
import argparse
import pathlib
import struct
import sys

import blobfmt

EXPECTED_ORDER = ("conv_w", "conv_b", "dw_w", "dw_b", "fc_w", "fc_b")


def parse_blob(data: bytes):
    """Read the **constant** slots out of a v2 graph blob.

    The nodes are skipped on purpose: this script bakes weights and input into a C
    header, and the frozen target chain spells its own graph out in C. What it must
    not do is carry a second copy of the slot layout -- `blobfmt` owns that, and a v1
    blob (24-byte tensor header) is rejected there instead of being misparsed.
    """
    tensors = blobfmt.parse_constants(data)
    missing = [n for n in EXPECTED_ORDER if n not in tensors]
    if missing:
        raise SystemExit(f"emit_k2_model_header: blob is missing {missing}")
    return tensors


def emit_array(fh, name: str, values) -> None:
    fh.write(f"static const float {name}[{len(values)}] = {{\n")
    for start in range(0, len(values), 6):
        chunk = ", ".join(f"{v:.9e}F" for v in values[start:start + 6])
        fh.write(f"    {chunk},\n")
    fh.write("};\n\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("blob")
    ap.add_argument("input")
    ap.add_argument("out")
    args = ap.parse_args()

    tensors = parse_blob(pathlib.Path(args.blob).read_bytes())
    raw = pathlib.Path(args.input).read_bytes()
    if len(raw) % 4:
        raise SystemExit("emit_k2_model_header: input is not fp32")
    input_values = struct.unpack(f"<{len(raw) // 4}f", raw)

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as fh:
        fh.write("/* Generated by emit_k2_model_header.py -- do not edit.\n"
                 " * k2_conv_micro weights and input, decoded from the repository blob. */\n\n")
        for name in EXPECTED_ORDER:
            emit_array(fh, f"kat_k2_{name}", tensors[name])
        emit_array(fh, "kat_k2_input", input_values)
    print(f"[emit_k2_model_header] wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
