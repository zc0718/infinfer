#!/usr/bin/env python3
"""Turn the emitter's expectation blob into a C header the targets include.

Blob layout (little endian, written by `kat_driver.c` in KAT_EMIT mode):
  4 bytes  magic "KATR"
  4 bytes  element count (u32)
  1 byte   per element of the first checked tensor (int8)
  4 bytes  per element of the second checked tensor (float bits)

The header keeps the raw bytes rather than float literals: a literal would have
to be re-parsed by the target's libc, and `%a`/`1e-7` round-tripping is exactly
the kind of thing that silently differs between newlib and glibc.
"""
import argparse
import hashlib
import pathlib
import struct
import sys

MAGIC = b"KATR"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("blob", help="expectation blob written by the KAT_EMIT build")
    ap.add_argument("out", help="header to write")
    ap.add_argument("--id", default="kat", help="image id recorded in the header")
    args = ap.parse_args()

    data = pathlib.Path(args.blob).read_bytes()
    if data[:4] != MAGIC:
        print(f"emit_kat_image: bad magic {data[:4]!r}", file=sys.stderr)
        return 1
    (count,) = struct.unpack("<I", data[4:8])
    payload = data[8:]
    if len(payload) != count:
        print(f"emit_kat_image: expected {count} payload bytes, got {len(payload)}",
              file=sys.stderr)
        return 1

    sha = hashlib.sha256(payload).hexdigest()
    out = [
        "/* Generated by workspace/qa/prep/emit_kat_image.py -- do not edit.",
        " * Regenerate: build the KAT_EMIT driver, run it, re-run the emitter.",
        " * 由 workspace/qa/prep/emit_kat_image.py 生成，不要手改。 */",
        "#pragma once",
        "",
        f'#define KAT_IMAGE_ID "{args.id}"',
        f"#define KAT_EXPECT_LEN {count}u",
        f'#define KAT_IMAGE_SHA256 "{sha}"',
        "",
        "static const unsigned char kat_expect_bytes[KAT_EXPECT_LEN] = {",
    ]
    row = []
    for byte in payload:
        row.append(f"0x{byte:02X}")
        if len(row) == 12:
            out.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("    " + ", ".join(row) + ",")
    out += ["};", ""]

    path = pathlib.Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"[emit_kat_image] wrote {path} (id={args.id}, n={count}, sha256={sha[:16]}...)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
